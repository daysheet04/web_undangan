create or replace function public.set_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = timezone('utc', now()); return new; end;
$$;

create table public.templates (
  id bigint generated by default as identity primary key, code varchar(50) not null unique,
  name varchar(100) not null, category varchar(50) not null, description varchar(255) not null,
  thumbnail varchar(255), is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()), updated_at timestamptz not null default timezone('utc', now())
);
create table public.template_packages (
  id bigint generated by default as identity primary key, template_id bigint not null references public.templates(id) on delete cascade,
  code varchar(30) not null, name varchar(80) not null, tagline varchar(180) not null, price numeric(12,2) not null default 0,
  gallery_limit smallint not null default 2 check (gallery_limit between 1 and 20), has_music boolean not null default false,
  has_gift boolean not null default false, has_wishes boolean not null default false, sort_order smallint not null default 0,
  is_active boolean not null default true, created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()), unique (template_id, code)
);
create table public.orders (
  id bigint generated by default as identity primary key, order_code varchar(32) not null unique,
  template_id bigint not null references public.templates(id), package_id bigint not null references public.template_packages(id),
  customer_name varchar(120) not null, customer_email varchar(254) not null, customer_phone varchar(24) not null, editor_token varchar(128) not null unique,
  status varchar(24) not null default 'waiting_payment' check (status in ('waiting_payment','editing','published','cancelled')),
  payment_status varchar(24) not null default 'pending' check (payment_status in ('pending','paid','failed','expired','refunded')),
  editor_email_sent_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()), updated_at timestamptz not null default timezone('utc', now())
);
create table public.invitations (
  id bigint generated by default as identity primary key, order_id bigint not null unique references public.orders(id) on delete cascade,
  slug varchar(120) unique, groom_full_name varchar(150), groom_nickname varchar(80), groom_father varchar(150), groom_mother varchar(150),
  bride_full_name varchar(150), bride_nickname varchar(80), bride_father varchar(150), bride_mother varchar(150),
  akad_date date, akad_start_time time, akad_end_time time, reception_date date, reception_start_time time, reception_end_time time,
  venue_name varchar(180), venue_address text, maps_url varchar(500), love_story text, instagram varchar(100),
  cover_image varchar(255), groom_photo varchar(255), bride_photo varchar(255), music_file varchar(255), music_title varchar(150),
  published_at timestamptz, created_at timestamptz not null default timezone('utc', now()), updated_at timestamptz not null default timezone('utc', now())
);
create table public.invitation_media (
  id bigint generated by default as identity primary key, invitation_id bigint not null references public.invitations(id) on delete cascade,
  file_path varchar(255) not null, sort_order smallint not null default 0, created_at timestamptz not null default timezone('utc', now())
);
create table public.gift_accounts (
  id bigint generated by default as identity primary key, invitation_id bigint not null references public.invitations(id) on delete cascade,
  provider varchar(80) not null, account_number varchar(100) not null, account_name varchar(150) not null, label varchar(100),
  sort_order smallint not null default 0, is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()), updated_at timestamptz not null default timezone('utc', now())
);
create table public.invitation_guests (
  id bigint generated by default as identity primary key, invitation_id bigint not null references public.invitations(id) on delete cascade,
  guest_name varchar(150) not null, salutation varchar(80) not null default 'Bapak/Ibu/Saudara/i', guest_token varchar(64) not null unique,
  created_at timestamptz not null default timezone('utc', now())
);
create table public.guest_messages (
  id bigint generated by default as identity primary key, invitation_id bigint not null references public.invitations(id) on delete cascade,
  guest_name varchar(120) not null, attendance_status varchar(24) not null check (attendance_status in ('attending','not_attending','unsure')),
  guest_count smallint not null default 1 check (guest_count between 1 and 10), message varchar(500) not null,
  is_approved boolean not null default true, created_at timestamptz not null default timezone('utc', now())
);
create table public.payments (
  id bigint generated by default as identity primary key, order_id bigint not null unique references public.orders(id) on delete cascade,
  gateway varchar(50), gateway_order_id varchar(64) unique, transaction_id varchar(120) unique,
  snap_token text, snap_redirect_url text, payment_type varchar(50), amount numeric(12,2) not null default 0,
  status varchar(24) not null default 'pending' check (status in ('pending','paid','failed','expired','refunded')), paid_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()), updated_at timestamptz not null default timezone('utc', now())
);

drop function if exists public.create_daymoment_order(varchar,bigint,bigint,varchar,varchar,varchar,numeric);
drop function if exists public.create_daymoment_order(varchar,bigint,bigint,varchar,varchar,varchar,varchar,numeric);
create function public.create_daymoment_order(
  p_order_code varchar, p_template_id bigint, p_package_id bigint,
  p_customer_name varchar, p_customer_phone varchar, p_customer_email varchar, p_editor_token varchar, p_amount numeric
) returns bigint language plpgsql security definer set search_path = public as $$
declare new_order_id bigint;
begin
  insert into public.orders (order_code,template_id,package_id,customer_name,customer_phone,customer_email,editor_token)
  values (p_order_code,p_template_id,p_package_id,p_customer_name,p_customer_phone,p_customer_email,p_editor_token)
  returning id into new_order_id;
  insert into public.invitations (order_id) values (new_order_id);
  insert into public.payments (order_id,amount) values (new_order_id,p_amount);
  return new_order_id;
end;
$$;
revoke all on function public.create_daymoment_order(varchar,bigint,bigint,varchar,varchar,varchar,varchar,numeric) from public, anon, authenticated;
grant execute on function public.create_daymoment_order(varchar,bigint,bigint,varchar,varchar,varchar,varchar,numeric) to service_role;


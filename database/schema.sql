-- Realtime publik hanya boleh membaca konten undangan yang memang sudah terbit.
create or replace function public.is_published_invitation(p_invitation_id bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.invitations i join public.orders o on o.id = i.order_id
    where i.id = p_invitation_id and i.published_at is not null and o.status = 'published'
  );
$$;
revoke all on function public.is_published_invitation(bigint) from public;
grant execute on function public.is_published_invitation(bigint) to anon, authenticated, service_role;

create policy public_read_published_invitations on public.invitations for select to anon
using (public.is_published_invitation(id));
create policy public_read_approved_messages on public.guest_messages for select to anon
using (is_approved and public.is_published_invitation(invitation_id));
create policy public_read_published_gifts on public.gift_accounts for select to anon
using (is_active and public.is_published_invitation(invitation_id));
create policy public_read_published_media on public.invitation_media for select to anon
using (public.is_published_invitation(invitation_id));


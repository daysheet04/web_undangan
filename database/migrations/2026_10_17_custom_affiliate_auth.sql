-- Affiliate identity owned by Daymoment. Supabase is used as PostgreSQL only;
-- no records in auth.users are required by this authentication flow.
create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.affiliate_accounts (
  id uuid primary key default gen_random_uuid(),
  email varchar(254) not null unique,
  password_hash text not null,
  full_name varchar(120) not null,
  phone varchar(24) not null,
  referral_code varchar(32) not null unique,
  status varchar(20) not null default 'pending'
    check (status in ('pending', 'active', 'suspended', 'rejected')),
  email_verified_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint affiliate_email_is_normalized check (email = lower(trim(email)))
);

create table if not exists public.affiliate_email_verifications (
  id uuid primary key default gen_random_uuid(),
  affiliate_id uuid not null references public.affiliate_accounts(id) on delete cascade,
  token_hash char(64) not null unique,
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.affiliate_sessions (
  id uuid primary key default gen_random_uuid(),
  affiliate_id uuid not null references public.affiliate_accounts(id) on delete cascade,
  token_hash char(64) not null unique,
  ip_address text,
  user_agent varchar(500),
  expires_at timestamptz not null,
  revoked_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  last_seen_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.affiliate_login_history (
  id bigint generated by default as identity primary key,
  affiliate_id uuid references public.affiliate_accounts(id) on delete set null,
  email varchar(254) not null,
  success boolean not null,
  failure_reason varchar(50),
  ip_address text,
  user_agent varchar(500),
  attempted_at timestamptz not null default timezone('utc', now())
);

create index if not exists idx_affiliate_accounts_status on public.affiliate_accounts(status, created_at desc);
create index if not exists idx_affiliate_verifications_affiliate on public.affiliate_email_verifications(affiliate_id, created_at desc);
create index if not exists idx_affiliate_sessions_active on public.affiliate_sessions(token_hash, expires_at) where revoked_at is null;
create index if not exists idx_affiliate_login_rate_limit on public.affiliate_login_history(email, attempted_at desc) where success is false;

create or replace function public.register_affiliate_account(
  p_full_name text,
  p_phone text,
  p_email text,
  p_password text,
  p_verification_token_hash text,
  p_verification_expires_at timestamptz
)
returns table(id uuid, email varchar, full_name varchar, status varchar)
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  new_id uuid := gen_random_uuid();
  normalized_email text := lower(trim(p_email));
  base_code text;
  final_code text;
begin
  base_code := upper(regexp_replace(coalesce(p_full_name, 'PARTNER'), '[^a-zA-Z0-9]', '', 'g'));
  base_code := left(coalesce(nullif(base_code, ''), 'PARTNER'), 10);
  final_code := base_code || upper(substr(replace(new_id::text, '-', ''), 1, 7));

  insert into public.affiliate_accounts (
    id, email, password_hash, full_name, phone, referral_code
  ) values (
    new_id,
    normalized_email,
    crypt(p_password, gen_salt('bf', 12)),
    left(trim(p_full_name), 120),
    left(trim(p_phone), 24),
    final_code
  );

  insert into public.affiliate_email_verifications (
    affiliate_id, token_hash, expires_at
  ) values (
    new_id, p_verification_token_hash, p_verification_expires_at
  );

  return query
  select account.id, account.email, account.full_name, account.status
  from public.affiliate_accounts account
  where account.id = new_id;
exception
  when unique_violation then
    raise exception using errcode = '23505', message = 'affiliate_email_exists';
end;
$$;

create or replace function public.verify_affiliate_password(p_email text, p_password text)
returns table(id uuid, email varchar, full_name varchar, phone varchar, referral_code varchar, status varchar)
language sql
security definer
set search_path = public, extensions
as $$
  select account.id, account.email, account.full_name, account.phone, account.referral_code, account.status
  from public.affiliate_accounts account
  where account.email = lower(trim(p_email))
    and account.password_hash = crypt(p_password, account.password_hash)
  limit 1;
$$;

create or replace function public.activate_affiliate_account(p_token_hash text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  target_affiliate_id uuid;
  activated_rows integer;
begin
  select verification.affiliate_id
    into target_affiliate_id
  from public.affiliate_email_verifications verification
  where verification.token_hash = p_token_hash
    and verification.used_at is null
    and verification.expires_at > timezone('utc', now())
  for update;

  if target_affiliate_id is null then return false; end if;

  update public.affiliate_email_verifications
  set used_at = timezone('utc', now())
  where token_hash = p_token_hash;

  update public.affiliate_accounts
  set status = 'active',
      email_verified_at = coalesce(email_verified_at, timezone('utc', now())),
      updated_at = timezone('utc', now())
  where id = target_affiliate_id and status = 'pending';

  get diagnostics activated_rows = row_count;
  return activated_rows = 1;
end;
$$;


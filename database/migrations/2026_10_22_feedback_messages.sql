-- Migration: Feedback & suggestions table for client critiques and recommendations
create table if not exists public.feedback_messages (
  id bigint generated by default as identity primary key,
  name varchar(120) not null,
  message text not null,
  created_at timestamptz not null default timezone('utc', now())
);

create index if not exists idx_feedback_created_at on public.feedback_messages(created_at desc);

alter table public.feedback_messages enable row level security;
grant all privileges on public.feedback_messages to service_role;
